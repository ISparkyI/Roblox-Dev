// Станція ролу: пульт із похилим екраном (3 картки) + бокова тумба з важелем. Блоковий стиль, правило 0,1 (дрібні деталі) / 0,5 (великі маси).
// Одиниці — стади, опора — центр низу, гравець стоїть з боку +Z (екран дивиться на +Z і вгору).
const THREE = global.THREE || require('/tmp/three/node_modules/three');
const D = Math.PI / 180;
const M = (p = [0, 0, 0], r = [0, 0, 0]) => new THREE.Matrix4().compose(new THREE.Vector3(...p),
  new THREE.Quaternion().setFromEuler(new THREE.Euler(r[0] * D, r[1] * D, r[2] * D, 'XYZ')), new THREE.Vector3(1, 1, 1));
const C = {
  steel: '5a616c', steelD: '3a3f48', steelL: '8a929c', ink: '24272d', wood: '664e42', woodD: '4f3a30', woodL: '8a6a52',
  brass: 'f2c14b', red: 'e8463c', redD: 'a82a24', screen: '1a1d22', glass: '2a2f36', lamp: 'ffd34d', lime: '9bff3a', brassD: 'c4932c', ink2: '1c1f24', white: 'fff6ec',
};
// екран: похилий прямокутник; кут нахилу і розмір — для текстури панелі
const SCREEN = { w: 7.6, h: 4.0, tilt: 34, cx: -1.75, cy: 4.05, cz: 0.6 };
function build() {
  const parts = [];
  const add = (t, s, m, c, tag) => { parts.push({ t, s: s.slice(), m: m.elements.slice(), c, tag }); return m; };
  const F = (p, r, P) => (P ? P.clone() : new THREE.Matrix4()).multiply(M(p, r));
  const b = (s, p, r, c, P, tag) => add('b', s, F(p, r, P), c, tag);
  const w = (s, p, r, c, P, tag) => add('w', s, F(p, r, P), c, tag);

  // ===== цоколь (ширший за пульт на 0,5 з усіх боків) =====
  b([12.6, 0.6, 7.2], [0, 0.3, 0], [0, 0, 0], C.steelD);
  // ===== корпус пульта (ліва частина): брусок + клин зверху (похилий верх) =====
  const BX = -1.75, BW = 8.4, BD = 5.4, WH = 3.6; // WH — висота клина (похилого верху)
  b([BW, 2.6, BD], [BX, 0.6 + 1.3, -0.3], [0, 0, 0], C.wood);
  w([BW, WH, BD], [BX, 0.6 + 2.6 + WH / 2, -0.3], [0, 180, 0], C.wood);   // клин: високий край ззаду (−Z), схил до гравця
  // дерев'яні дошки-накладки спереду (виступ 0,1+)
  for (let i = 0; i < 4; i++) b([BW - 0.6, 0.5, 0.3], [BX, 1.05 + i * 0.62, 2.5], [0, 0, 0], i % 2 ? C.woodD : C.woodL);
  // металеві кутники на ребрах
  for (const sx of [-1, 1]) {
    b([0.6, 2.9, 0.6], [BX + sx * (BW / 2 - 0.05), 0.6 + 1.45, 2.35], [0, 0, 0], C.steel);
    b([0.6, 2.6 + WH, 0.6], [BX + sx * (BW / 2 - 0.05), 0.6 + (2.6 + WH) / 2, -2.95], [0, 0, 0], C.steel);
  }
  b([BW + 0.4, 0.5, 0.6], [BX, 0.6 + 2.6 + WH, -2.95], [0, 0, 0], C.steelD); // верхня балка ззаду
  // ===== рамка екрана на схилі =====
  // площина схилу проходить через центр клина; нормаль схилу = вгору й до гравця → поворот рамки на −(90° − кут схилу) навколо X
  const slope = Math.atan2(WH, BD) / D; // ≈ 33.7°
  const S = F([BX, 0.6 + 2.6 + WH / 2, -0.3], [-(90 - slope), 0, 0]);
  const nz = 0;
  b([SCREEN.w + 0.9, 4.75, 0.4], [0, 0, 0.1], [0, 0, 0], C.steelD, S);         // рама
  b([SCREEN.w + 0.1, 4.0, 0.4], [0, 0, 0.3], [0, 0, 0], C.screen, S, 'screen');  // екран (на ньому SurfaceGui / текстура)
  // заклепки рами
  for (const [x, y] of [[-1, -1], [1, -1], [-1, 1], [1, 1]]) b([0.3, 0.3, 0.3], [x * (SCREEN.w / 2 + 0.2), y * 2.15, 0.35], [0, 0, 45], C.brass, S);
  // ===== лампи над екраном: по одній над кожною карткою (світить над вибраною) =====
  for (let i = -1; i <= 1; i++) {
    const L = F([BX + i * 2.55, 0.6 + 2.6 + WH + 0.25, -2.95], [0, 0, 0]);
    // L — верх балки: основа втоплена в балку на 0,1, лампа сидить на основі, кришка — на лампі
    b([0.9, 0.4, 0.9], [0, 0.1, 0], [0, 0, 0], C.ink, L);
    b([0.7, 0.6, 0.7], [0, 0.52, 0], [0, 0, 0], i === -1 ? C.lime : C.glass, L, i === -1 ? 'lampOn' : 'lampOff');
    b([0.9, 0.2, 0.9], [0, 0.86, 0], [0, 0, 0], C.ink, L);
  }

  // ===== тумба важеля (права частина): машина з механізмом =====
  const TX = 4.45, TW = 3.1, TZ = 0.6, TD = 4.4, TY0 = 0.6, TH = 2.9;
  // корпус + верхній скіс спереду (клин) — тумба не «коробка», а пульт машини
  b([TW, TH - 0.6, TD], [TX, TY0 + (TH - 0.6) / 2, TZ], [0, 0, 0], C.steel);
  w([TW, 0.6, 0.9], [TX, TY0 + TH - 0.3, TZ + TD / 2 - 0.45], [0, 180, 0], C.steel);
  b([TW, 0.6, TD - 0.9], [TX, TY0 + TH - 0.3, TZ - 0.45], [0, 0, 0], C.steel);
  // ніжки-опори по кутах (виступають з корпусу)
  for (const sx of [-1, 1]) for (const sz of [-1, 1]) b([0.6, 0.8, 0.6], [TX + sx * (TW / 2 - 0.2), TY0 + 0.4, TZ + sz * (TD / 2 - 0.2)], [0, 0, 0], C.steelD);
  // бічні панелі з заклепками (обидва боки)
  for (const sx of [-1, 1]) {
    b([0.3, 1.6, 3.2], [TX + sx * (TW / 2 + 0.05), TY0 + 1.3, TZ - 0.1], [0, 0, 0], C.steelL);
    for (const [dy, dz] of [[-0.6, -1.3], [0.6, -1.3], [-0.6, 1.1], [0.6, 1.1]]) b([0.2, 0.25, 0.25], [TX + sx * (TW / 2 + 0.2), TY0 + 1.3 + dy, TZ - 0.1 + dz], [0, 0, 0], C.brass);
  }
  // шестерня збоку (зовнішній бік): два бруски, повернуті на 45° = восьмикутник, зуби, вісь
  const G = F([TX + TW / 2 + 0.45, TY0 + 1.55, TZ - 0.1], [0, 0, 0]);
  b([0.3, 1.5, 1.5], [0, 0, 0], [0, 0, 0], C.brass, G, 'gear');
  b([0.3, 1.5, 1.5], [0, 0, 0], [45, 0, 0], C.brass, G, 'gear');
  for (let k = 0; k < 8; k++) b([0.3, 0.35, 0.4], [0, 0, 0], [k * 45 + 22.5, 0, 0], C.brassD, G.clone().multiply(M([0, 0, 0], [k * 45 + 22.5, 0, 0])).multiply(M([0, 0.9, 0])), 'gear');
  b([0.5, 0.5, 0.5], [0.1, 0, 0], [0, 0, 0], C.steelD, G);
  // фронт: рамка з табло-індикатором і смугою «небезпека» (прямі смуги в темній рамці)
  const FZ = TZ + TD / 2;
  b([TW - 0.4, 2.0, 0.3], [TX, TY0 + 1.25, FZ + 0.05], [0, 0, 0], C.ink);                // рамка
  b([TW - 0.9, 0.7, 0.3], [TX, TY0 + 1.75, FZ + 0.15], [0, 0, 0], C.lime, null, 'lampOn'); // індикатор
  for (let i = 0; i < 5; i++) b([0.42, 0.6, 0.3], [TX - 0.9 + i * 0.45, TY0 + 0.7, FZ + 0.15], [0, 0, 0], i % 2 ? C.ink2 : C.brass);
  // ===== механізм важеля зверху: восьмикутна основа, напрямні пазу =====
  const TOP = TY0 + TH;
  b([2.2, 0.3, 2.2], [TX, TOP + 0.1, TZ - 0.2], [0, 0, 0], C.steelD);
  b([2.2, 0.3, 2.2], [TX, TOP + 0.1, TZ - 0.2], [0, 45, 0], C.steelD);
  b([0.5, 0.3, 2.6], [TX, TOP + 0.3, TZ - 0.2], [0, 0, 0], C.ink2);                       // паз
  for (const sx of [-1, 1]) b([0.3, 0.5, 2.8], [TX + sx * 0.45, TOP + 0.4, TZ - 0.2], [0, 0, 0], C.steelL); // напрямні
  // важіль: втулка-шарнір, вал, муфта, кругла рукоятка (брусок + повернутий округлювач) з бліком
  const LV = F([TX, TOP + 0.45, TZ - 0.2], [-28, 0, 0]);
  b([1.3, 0.7, 0.7], [0, 0.1, 0], [0, 0, 0], C.steel, LV, 'hinge');
  b([0.4, 3.0, 0.4], [0, 1.7, 0], [0, 0, 0], C.steelL, LV, 'lever');
  b([0.6, 0.3, 0.6], [0, 2.6, 0], [0, 0, 0], C.ink, LV, 'lever');
  b([1.0, 1.0, 1.0], [0, 3.45, 0], [0, 0, 0], C.red, LV, 'knob');
  b([0.8, 1.2, 0.8], [0, 3.45, 0], [0, 45, 0], C.red, LV, 'knob');
  b([0.8, 0.8, 1.2], [0, 3.45, 0], [45, 0, 0], C.redD, LV, 'knob');
  b([0.25, 0.25, 0.25], [-0.3, 3.95, 0.3], [0, 0, 0], C.white, LV, 'knob');
  return parts;
}
module.exports = { build, C, SCREEN };
