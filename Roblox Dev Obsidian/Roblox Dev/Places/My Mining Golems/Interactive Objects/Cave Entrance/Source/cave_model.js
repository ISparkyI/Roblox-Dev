// Вхід у печеру «Golem Vault» — блоковий стиль (GDD: маси + округлювачі + шапки, мох, правило 0,5 для карт).
// Одиниці — стади. Опора: центр низу (y = 0). Вхід дивиться в +Z.
const THREE = global.THREE || require('/tmp/three/node_modules/three');
const D = Math.PI / 180;
const M = (p = [0, 0, 0], r = [0, 0, 0]) => new THREE.Matrix4().compose(new THREE.Vector3(...p),
  new THREE.Quaternion().setFromEuler(new THREE.Euler(r[0] * D, r[1] * D, r[2] * D, 'XYZ')), new THREE.Vector3(1, 1, 1));

const C = {
  rockL: '8a939e', rock: '7d8693', rockM: '6f7884', rockD: '5f6974', rockDD: '4a4d52',
  moss: '5a8f3c', mossL: '6a9e45', mossD: '467a2e',
  wood: '664e42', woodD: '5c463a', iron: '2f3236',
  dark0: '1a1c20', dark1: '0e0f12', dark2: '050506', glow: 'f2c14b', sign: '7a5a40',
};

function build() {
  const parts = [];
  const add = (t, s, m, c, tag) => { parts.push({ t, s: s.slice(), m: m.elements.slice(), c, tag }); return m; };
  let curTag = null;
  const b = (s, p, r, c, P, tag) => add('b', s, (P ? P.clone() : new THREE.Matrix4()).multiply(M(p, r)), c, tag || curTag);
  const w = (s, p, r, c, P) => add('w', s, (P ? P.clone() : new THREE.Matrix4()).multiply(M(p, r)), c);
  const F = (p, r, P) => (P ? P.clone() : new THREE.Matrix4()).multiply(M(p, r));
  // маса + округлювач (та сама маса, менша в XZ, повернута) — 0,5 всередині зверху й знизу
  const lump = (P, s, c, turn = 40, k = 0.82) => {
    const m = b(s, [0, s[1] / 2, 0], [0, 0, 0], c, P);
    b([s[0] * k, s[1] - 1.0, s[2] * k], [0, s[1] / 2, 0], [0, turn, 0], c, P);
    return m;
  };
  // мох-«шапочка» на верхній грані маси: плита з невеликим нахилом + менша зверху (виступ 0,5)
  const moss = (P, w0, d0, tilt = 4, c1 = C.moss, c2 = C.mossL) => {
    b([w0, 0.9, d0], [0, 0.2, 0], [tilt, 0, -tilt * 0.6], c1, P);
    b([w0 * 0.62, 0.9, d0 * 0.6], [0.2, 0.7, -0.1], [tilt * 0.5, 22, 0], c2, P);
  };

  // валун: маса + округлювач + шапка (зрізаний верх), усе повернуте; c2 — колір шапки
  const boulder = (p, r, s, c, c2) => {
    const P = F(p, r);
    lump(P, s, c, 40, 0.8);
    lump(F([0.15 * s[0], s[1] - 0.6, -0.05 * s[2]], [6, 25, -5], P), [s[0] * 0.62, Math.max(1.2, s[1] * 0.22), s[2] * 0.6], c2 || c, 44, 0.78);
    return P;
  };
  // мох, що лежить на валуні (шапочка, нахилена разом із ним)
  const mossOn = (P, y, w0, d0, tilt = 5) => moss(P.clone().multiply(M([0, y, 0], [0, 0, 0])), w0, d0, tilt);

  // ===== тіло пагорба: нижній ряд (опори арки) =====
  const L1 = boulder([-6.4, -0.6, -0.8], [0, -12, 3], [6.8, 9.6, 9.0], C.rock, C.rockL);
  const R1 = boulder([6.3, -0.6, -1.0], [0, 14, -3], [6.4, 8.6, 8.6], C.rockM, C.rock);
  boulder([0, -0.6, -5.2], [0, 6, 0], [13.0, 10.6, 4.6], C.rockD, C.rockM);           // задня стіна
  // ===== верхній ряд: склепіння з трьох валунів, що сходяться до верхівки =====
  const T1 = boulder([-3.8, 7.6, -1.2], [4, 24, -10], [6.4, 4.2, 7.6], C.rock, C.rockL);
  const T2 = boulder([3.6, 7.2, -1.4], [-3, -20, 9], [6.2, 4.0, 7.4], C.rockM, C.rock);
  const T3 = boulder([0.2, 10.4, -1.8], [5, 38, -3], [6.8, 3.4, 6.6], C.rockL, C.rockL);
  mossOn(T3, 3.9, 6.0, 5.2, 4);
  mossOn(T1, 4.6, 4.2, 5.0, 7);
  mossOn(T2, 4.3, 3.8, 4.6, -6);
  // моховий наплив, що звисає з верху над входом
  b([7.6, 1.4, 1.6], [0.2, 10.5, 3.4], [-16, -4, 2], C.mossD);
  b([3.2, 1.0, 1.2], [-1.6, 9.6, 3.8], [-22, 8, 4], C.moss);
  b([2.4, 0.9, 1.1], [2.6, 9.8, 3.7], [-20, -12, -3], C.mossL);
  // ліани: тонкі зелені смуги звисають з краю над входом (як на карті)
  for (const [x, h, ry, col] of [[-5.6, 3.6, 8, C.moss], [-4.9, 2.2, -6, C.mossL], [5.4, 3.0, -10, C.mossD], [6.1, 1.8, 12, C.moss]]) {
    b([0.5, h, 0.5], [x, 9.6 - h / 2, 4.3], [6, ry, 0], col);
  }
  // накладки-плити на фасаді опор (рвуть рівні площини, дають сходинки світла й тіні)
  b([2.6, 3.4, 1.4], [-7.6, 2.4, 3.8], [4, -14, 6], C.rockM);
  b([2.0, 2.4, 1.4], [-5.8, 6.4, 3.6], [-6, 10, -8], C.rockL);
  b([2.4, 3.0, 1.4], [7.4, 2.8, 3.6], [-3, 16, -5], C.rockD);
  b([1.8, 2.2, 1.4], [5.9, 6.0, 3.4], [5, -12, 9], C.rock);
  // ===== бокові валуни (крила пагорба) =====
  const W1 = boulder([-10.6, -0.6, 0.4], [0, 32, 6], [4.6, 6.0, 5.0], C.rockM, C.rock);
  mossOn(W1, 6.2, 3.2, 3.2, 8);
  boulder([10.4, -0.6, 0.2], [0, -28, -7], [4.2, 5.0, 4.6], C.rock, C.rockL);
  // ===== дрібні валуни біля входу (як на референсі) =====
  boulder([-5.4, -0.4, 4.6], [0, 18, 4], [2.4, 2.2, 2.2], C.rockD, C.rockM);
  boulder([-7.4, -0.4, 5.6], [0, -30, -5], [1.6, 1.4, 1.6], C.rockM);
  boulder([5.2, -0.4, 4.8], [0, -22, -4], [2.2, 1.9, 2.0], C.rockM, C.rock);
  boulder([7.0, -0.4, 6.0], [0, 40, 3], [1.4, 1.2, 1.4], C.rockD);
  // поріг перед входом — пласка кам'яна плита, трохи втоплена
  lump(F([0, -0.4, 3.6], [0, 4, 0]), [7.4, 0.9, 3.0], C.rockD, 36, 0.86);

  // ===== темний прохід (затемнення вглиб: три «рамки» від темно-сірого до чорного) =====
  b([6.6, 8.7, 1.6], [0, 3.85, 2.9], [0, 0, 0], C.dark0, null, 'dark');   // устя
  b([5.6, 8.4, 2.6], [0, 3.2, 1.0], [0, 0, 0], C.dark1, null, 'dark');   // глибше
  b([4.6, 8.1, 4.0], [0, 2.55, -1.6], [0, 0, 0], C.dark2, null, 'dark');  // найтемніше
  // склепіння проходу — скоси з клинів, що закруглюють верхні кути
  w([1.6, 1.6, 1.4], [-2.6, 7.4, 3.1], [0, 90, 180], C.rockM);
  w([1.6, 1.6, 1.4], [2.6, 7.4, 3.1], [0, -90, 180], C.rockM);

  // ===== дерев'яне кріплення шахти в отворі (дрібні деталі — правило 0,1 між собою) =====
  curTag = 'prop';
  b([0.9, 7.6, 0.9], [-3.5, 4.4, 3.9], [0, 0, 2], C.wood);
  b([0.9, 7.6, 0.9], [3.5, 4.4, 3.9], [0, 0, -2], C.wood);
  b([9.2, 1.0, 1.3], [0, 8.4, 4.0], [0, 0, -1.5], C.woodD);
  // скоби
  b([1.4, 0.5, 1.2], [-3.5, 7.4, 3.9], [0, 0, 2], C.iron);
  b([1.4, 0.5, 1.2], [3.5, 7.4, 3.9], [0, 0, -2], C.iron);
  // ліхтарі на стовпах
  for (const sx of [-1, 1]) {
    const P = F([sx * 4.5, 6.3, 4.4], [0, 0, 0]);
    b([0.9, 1.2, 0.9], [0, 0, 0], [0, 0, 0], C.glow, P, 'lamp');
    b([1.3, 0.5, 1.3], [0, 0.85, 0], [0, 0, 0], C.iron, P);
    b([1.1, 0.4, 1.1], [0, -0.75, 0], [0, 0, 0], C.iron, P);
    b([0.6, 0.4, 0.4], [-sx * 0.75, 0.7, 0], [0, 0, 0], C.iron, P);
  }
  curTag = null;
  return parts;
}
module.exports = { build, C };
